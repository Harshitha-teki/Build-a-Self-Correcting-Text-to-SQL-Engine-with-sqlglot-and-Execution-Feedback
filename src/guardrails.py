"""Phase 2 :: AST guardrails and syntax validation.

This module is the first gate in the pipeline. It answers two questions before
SQL is ever allowed to touch the database:

1. Is the string syntactically valid PostgreSQL? (sqlglot ``parse_one``)
2. Is it a read-only ``SELECT`` (or a statement whose top level *is* a SELECT,
   such as a ``WITH ... SELECT`` CTE), and free of any destructive node
   (DROP / DELETE / UPDATE / INSERT / ALTER / TRUNCATE / CREATE ...)?

Only when both answers are yes do we return ``is_valid=True`` and a normalized
SQL string. Everything else becomes a *syntax* failure that feeds the syntax
repair prompt.
"""

from __future__ import annotations

import re
from typing import Dict, List, Optional

import sqlglot
from sqlglot import exp, parse_one
from sqlglot.errors import ParseError, TokenError

# Top-level expression classes we consider a safe, read-only query.
_SAFE_TOP_LEVEL = (exp.Select,)

# Any of these node types appearing anywhere in the AST is a hard reject. We
# check node types rather than substrings so obfuscation (comments, casing,
# ``DELETE`` inside a string literal) cannot fool the guard. Resolve names
# defensively: sqlglot renames/moves node classes between releases.
_FORBIDDEN_NAMES = (
    "Drop",
    "Delete",
    "Update",
    "Insert",
    "Create",
    "Alter",
    "TruncateTable",
    "Truncate",
    "Command",
    "Merge",
    "Grant",
    "Copy",
)
_FORBIDDEN_NODE_TYPES = tuple(
    getattr(exp, name) for name in _FORBIDDEN_NAMES if hasattr(exp, name)
)

# Markdown code-fence stripper. LLMs love to wrap SQL in ```sql ... ``` blocks
# despite instructions; strip them *before* parsing.
_FENCE_RE = re.compile(r"```[a-zA-Z0-9_+-]*\s*(.*?)```", re.DOTALL)


def strip_markdown(sql_string: str) -> str:
    """Remove ``` fences / surrounding prose that break the parser.

    Returns the first fenced block if one exists, otherwise the trimmed input.
    """
    if not sql_string:
        return ""
    match = _FENCE_RE.search(sql_string)
    if match:
        return match.group(1).strip()
    return sql_string.strip()


def _collect_forbidden(nodes: List[exp.Expression]) -> Optional[exp.Expression]:
    for node in nodes:
        if isinstance(node, _FORBIDDEN_NODE_TYPES):
            return node
    return None


def validate_and_guard_sql(sql_string: str) -> Dict[str, object]:
    """Validate that SQL is safe (read-only SELECT) and syntactically correct.

    Params:
        sql_string (str): The raw SQL generated by the LLM.

    Returns:
        dict with keys:
            is_valid (bool): True only for a syntactically valid, read-only query.
            sql      (str) : Normalized SQL on success, else the (cleaned) input.
            error    (str) : Human-readable reason on failure, else None.
            failure_type (str): ``"syntax"`` when invalid, else None.

    Side effects: None.
    """
    cleaned = strip_markdown(sql_string)

    if not cleaned:
        return {
            "is_valid": False,
            "sql": sql_string,
            "error": "Syntax Error: empty SQL string.",
            "failure_type": "syntax",
        }

    # A statement may legally contain multiple semicolon-separated statements.
    # Enforce exactly one so a destructive tail cannot ride along.
    try:
        statements = sqlglot.parse(cleaned, read="postgres")
    except (ParseError, TokenError) as exc:
        return {
            "is_valid": False,
            "sql": cleaned,
            "error": f"Syntax Error: {exc}",
            "failure_type": "syntax",
        }

    statements = [s for s in statements if s is not None]
    if len(statements) == 0:
        return {
            "is_valid": False,
            "sql": cleaned,
            "error": "Syntax Error: no parseable statement found.",
            "failure_type": "syntax",
        }
    if len(statements) > 1:
        return {
            "is_valid": False,
            "sql": cleaned,
            "error": "Security Guardrail Violation: multiple statements are not permitted.",
            "failure_type": "syntax",
        }

    ast = statements[0]

    # Guardrail 1: only read-only top-level statements.
    if not isinstance(ast, _SAFE_TOP_LEVEL) and not isinstance(ast, exp.Union):
        return {
            "is_valid": False,
            "sql": cleaned,
            "error": (
                "Security Guardrail Violation: Only SELECT statements are "
                "permitted (SELECT / WITH ... SELECT / UNION)."
            ),
            "failure_type": "syntax",
        }

    # Guardrail 2: no destructive node buried anywhere in the tree.
    forbidden = _collect_forbidden(list(ast.walk()))
    if forbidden is not None:
        return {
            "is_valid": False,
            "sql": cleaned,
            "error": (
                "Security Guardrail Violation: statement contains a forbidden "
                f"operation ({type(forbidden).__name__.upper()}). Only read-only "
                "queries are permitted."
            ),
            "failure_type": "syntax",
        }

    # Success: return a normalized, dialect-stable rendering.
    try:
        normalized = ast.sql(dialect="postgres")
    except Exception:  # pragma: no cover - defensive; generation can throw
        normalized = cleaned

    return {
        "is_valid": True,
        "sql": normalized,
        "error": None,
        "failure_type": None,
    }
